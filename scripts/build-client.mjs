#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const ORDER = [
  'src/shared/constants.js',
  'src/client/styles.js',
  'src/client/rpc-client.js',
  'src/client/store.js',
  'src/client/components/CanvasSurface.js',
  'src/client/components/SessionChip.js',
  'src/client/entry.js',
];

function stripImportsAndExports(code) {
  return code
    .replace(/^import\s+[\s\S]*?from\s+['"][^'"]+['"];?\s*\n?/gm, '')
    .replace(/^export\s+(?=(?:async\s+)?function|const|let|var|class)/gm, '');
}

async function build() {
  const pkg = JSON.parse(await fs.readFile(path.join(ROOT, 'package.json'), 'utf8'));
  const parts = [];
  for (const rel of ORDER) {
    const raw = await fs.readFile(path.join(ROOT, rel), 'utf8');
    parts.push(`// --- ${rel} ---\n${stripImportsAndExports(raw).trim()}\n`);
  }

  const output = [
    '// Generated by scripts/build-client.mjs — do not edit directly.',
    'window.__ModuleLoader__.load({',
    `  id: ${JSON.stringify(pkg.name)},`,
    '  factory(require) {',
    "    const React = require('react');",
    '',
    parts.join('\n').replace(/^(?=.)/gm, '    '),
    '    return createClientPlugin(React);',
    '  },',
    '});',
    '',
  ].join('\n');

  const outPath = path.join(ROOT, 'client.js');
  await fs.writeFile(outPath, output, 'utf8');
  console.log(`Built ${outPath} (${Buffer.byteLength(output, 'utf8')} bytes)`);
}

build().catch((err) => {
  console.error(err);
  process.exit(1);
});
